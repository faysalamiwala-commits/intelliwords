def make_cover(title, author, color="Blue"):
    print("="*40)
    print(f"🎨 COVER READY!")
    print(f"📚 Title: {title}")
    print(f"✍️ Author: {author}")
    print(f"🎨 Color: {color}")
    print(f"📏 Size: 6x9 inch - Amazon KDP")
    print("="*40)
    print("✅ Cover created for KDP!")
    print("Made by IntelliWords - From Idea to Next Reader")

# Example
make_cover("My First Book", "Faysal Amiwala", "Royal Blue")
